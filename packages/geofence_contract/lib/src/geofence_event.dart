import 'geo_point.dart';
import 'geofence.dart';

/// Conceptual pickup workflow events.
///
/// These are NOT backend statuses; the backend decides which of them it
/// accepts and which change the pickup's status.
enum GeofenceEventType {
  pickupLocationEstablished(lifecycleRank: 0),
  collectorAssigned(lifecycleRank: 1),
  collectorApproaching(lifecycleRank: 2),

  /// Repeatable: a collector may enter/exit more than once.
  geofenceEntered(lifecycleRank: null),
  geofenceExited(lifecycleRank: null),

  collectorArrived(lifecycleRank: 3),
  collectionStarted(lifecycleRank: 4),
  collectionCompleted(lifecycleRank: 5),
  pickupClosed(lifecycleRank: 6);

  const GeofenceEventType({required this.lifecycleRank});

  /// Position in the pickup lifecycle for events that happen once per pickup;
  /// null for repeatable events.
  final int? lifecycleRank;

  bool get isOneShot => lifecycleRank != null;
}

/// Who produced an event.
enum GeofenceEventSource {
  /// The resident app. Never authoritative for collector events.
  resident,

  /// The collector app (detected on the collector's device; must be verified
  /// by the backend).
  collector,

  /// The backend (verified / authoritative).
  backend,
}

/// One workflow event.
///
/// [eventId] is generated by the producer ONCE and reused for every delivery
/// attempt, so the backend can deduplicate retries (idempotency key).
class GeofenceEvent {
  final String eventId;
  final String pickupId;
  final GeofenceEventType type;

  /// When the event happened (UTC), not when it was delivered.
  final DateTime occurredAt;

  final GeofenceEventSource source;

  final String? geofenceId;
  final int? geofenceVersion;

  /// Position at the time of the event, if relevant. A single point only; no
  /// location history is kept.
  final GeoPoint? location;

  /// Horizontal accuracy of [location] in meters, as reported by the device.
  final double? accuracyMeters;

  /// Collector or device identifier, only where the backend authorizes it.
  final String? actorId;

  GeofenceEvent({
    required this.eventId,
    required this.pickupId,
    required this.type,
    required DateTime occurredAt,
    required this.source,
    this.geofenceId,
    this.geofenceVersion,
    this.location,
    this.accuracyMeters,
    this.actorId,
  }) : occurredAt = occurredAt.toUtc() {
    if (eventId.isEmpty) {
      throw ArgumentError.value(eventId, 'eventId', 'must not be empty');
    }
    if (pickupId.isEmpty) {
      throw ArgumentError.value(pickupId, 'pickupId', 'must not be empty');
    }
    final acc = accuracyMeters;
    if (acc != null && (!acc.isFinite || acc < 0)) {
      throw ArgumentError.value(acc, 'accuracyMeters', 'must be >= 0');
    }
  }

  /// Local persistence format (e.g. for an offline outbox). This is NOT the
  /// backend wire format; map to the agreed contract with a
  /// [GeofenceWireMapper].
  Map<String, Object?> toStorageJson() => {
        'eventId': eventId,
        'pickupId': pickupId,
        'type': type.name,
        'occurredAt': occurredAt.toIso8601String(),
        'source': source.name,
        'geofenceId': geofenceId,
        'geofenceVersion': geofenceVersion,
        'lat': location?.latitude,
        'lng': location?.longitude,
        'accuracyMeters': accuracyMeters,
        'actorId': actorId,
      };

  factory GeofenceEvent.fromStorageJson(Map<String, Object?> json) {
    final lat = json['lat'] as num?;
    final lng = json['lng'] as num?;
    return GeofenceEvent(
      eventId: json['eventId'] as String,
      pickupId: json['pickupId'] as String,
      type: GeofenceEventType.values.byName(json['type'] as String),
      occurredAt: DateTime.parse(json['occurredAt'] as String),
      source: GeofenceEventSource.values.byName(json['source'] as String),
      geofenceId: json['geofenceId'] as String?,
      geofenceVersion: json['geofenceVersion'] as int?,
      location: (lat != null && lng != null)
          ? GeoPoint(lat.toDouble(), lng.toDouble())
          : null,
      accuracyMeters: (json['accuracyMeters'] as num?)?.toDouble(),
      actorId: json['actorId'] as String?,
    );
  }
}

/// Translates between these models and the backend's (not yet agreed) wire
/// format. Implement once the contract exists; nothing in either app should
/// depend on backend field names directly.
abstract interface class GeofenceWireMapper {
  Geofence decodeGeofence(Map<String, Object?> json);
  GeofenceEvent decodeEvent(Map<String, Object?> json);
  Map<String, Object?> encodeEvent(GeofenceEvent event);
}
